using System.Collections;
using System.Collections.Concurrent;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace FluentCss.Core;

public class ClassRegistry : IEnumerable<UtilityClass>
{
    /// <summary>
    /// Comment prepended to every generated stylesheet. It means the CSS is never
    /// empty and is easy to recognise in browser dev tools.
    /// </summary>
    private const string GeneratedHeader = "/* Generated by FluentCss */";

    public event EventHandler<UtilityClass>? OnClassAdded;
    private readonly ConcurrentSet<UtilityClass> _classes = new();

    // Rules are emitted in buckets so that variants always come after the rules
    // they are meant to override. Without this the shared registry could emit a
    // media variant (e.g. min-md:flex) before the base utility it overrides
    // (e.g. hidden), because classes are deduplicated in the order they were
    // first registered across the whole process.
    //
    // Only the media/non-media split is required: a pseudo (\:hover) or theme
    // (.theme-dark .x) selector already has a higher specificity than the base
    // rule, so it wins regardless of source order. Non-media rules therefore use
    // four buckets:
    //
    //   0 base, 1 pseudo, 2 theme, 3 theme + pseudo
    //
    // Media rules are kept as objects (not raw strings) so they can be sorted when
    // the stylesheet is emitted, following Tailwind: min-width variants ascending
    // (larger breakpoints win), max-width variants descending (smaller ranges win),
    // with min rules after max so min takes precedence when both match.
    private const int BucketCount = 4;
    private readonly StringBuilder[] _buckets;
    private readonly List<UtilityClass> _mediaClasses = new();

    // Registration order. GetEnumerator returns this so capturing the declarations of
    // an applied selector is deterministic: a ConcurrentDictionary does not preserve
    // insertion order, but ConcurrentQueue enumerates FIFO and is safe to enumerate
    // while it is written.
    private readonly ConcurrentQueue<UtilityClass> _orderedClasses = new();

    // Rules created by AddSelector. Non-media rules are emitted first, then the media
    // rules (sorted like the utility media rules), both before every utility rule so a
    // plain utility class can still override them.
    private readonly List<SelectorRule> _selectorRules = new();
    private readonly List<SelectorRule> _selectorMediaRules = new();

    private readonly object _cssBuilderLock = new();
    private readonly ConcurrentLazyObject<string> _cssObject;
    private readonly ConcurrentLazyObject<byte[]> _bytesObject;
    private readonly ConcurrentLazyObject<byte[]> _sha256Object;
    private readonly ConcurrentLazyObject<string> _sha256HexObject;

#if DEBUG
    private static int _rerenderCounter;
#endif

    public string Css => _cssObject.Get();

    public byte[] CssUtf8 => _bytesObject.Get();
    public byte[] Sha256 => _sha256Object.Get();
    public string Sha256Hex => _sha256HexObject.Get();

    public static ClassRegistry DefaultRegistry { get; } = new();

    public ClassRegistry()
    {
        _buckets = new StringBuilder[BucketCount];

        for (int i = 0; i < BucketCount; i++)
        {
            _buckets[i] = new StringBuilder();
        }

        _cssObject = new(() =>
        {
            lock (_cssBuilderLock)
            {
#if DEBUG
                int rerenderCount = Interlocked.Increment(ref _rerenderCounter);
                Console.WriteLine($"Rerender CSS counter: {rerenderCount}");
#endif

                StringBuilder result = StringBuilderBag.TakeOrNew();

                result.AppendLine(GeneratedHeader);

                AppendSelectorRules(result);

                for (int i = 0; i < BucketCount; i++)
                {
                    result.Append(_buckets[i]);
                }

                AppendMedia(result);

                string css = result.ToString();
                StringBuilderBag.ClearAndReturn(result);

                return css;
            }
        });
        _bytesObject = new(() => Encoding.UTF8.GetBytes(Css));
        _sha256Object = new(() => ComputeSha256(CssUtf8));
        _sha256HexObject = new(() => ToHex(Sha256));
    }

    public bool Add(UtilityClass c)
    {
        if (!_classes.TryAdd(c))
        {
            return false;
        }

        _orderedClasses.Enqueue(c);

        lock (_cssBuilderLock)
        {
            if (!string.IsNullOrWhiteSpace(c.MediaQuery))
            {
                _mediaClasses.Add(c);
            }
            else
            {
                StringBuilder bucket = _buckets[BucketIndex(c)];
                bucket.Append('\n');
                bucket.Append(c.CssString);
            }
        }

        InvalidateCaches();

        EventHandler<UtilityClass>? handler = OnClassAdded;
        handler?.Invoke(this, c);

        return true;
    }

    private void InvalidateCaches()
    {
        _cssObject.Invalidate();
        _bytesObject.Invalidate();
        _sha256Object.Invalidate();
        _sha256HexObject.Invalidate();
    }

    private static byte[] ComputeSha256(byte[] bytes)
    {
        using SHA256 sha = SHA256.Create();
        return sha.ComputeHash(bytes);
    }

    private static string ToHex(byte[] bytes) =>
        BitConverter.ToString(bytes).Replace("-", string.Empty).ToLowerInvariant();

    private static int BucketIndex(UtilityClass c)
    {
        // Media variants are emitted separately (and sorted) by AppendMedia.
        bool themed = !string.IsNullOrWhiteSpace(c.Theme);
        bool pseudo = !string.IsNullOrWhiteSpace(c.Pseudo);

        if (themed)
        {
            return pseudo ? 3 : 2;
        }

        return pseudo ? 1 : 0;
    }

    /// <summary>
    /// Appends the media rules in a deterministic order that matches Tailwind's
    /// mobile-first behaviour:
    /// <list type="bullet">
    /// <item>max-width rules first, descending by width (smaller ranges win);</item>
    /// <item>min-width rules last, ascending by width (larger breakpoints win);</item>
    /// <item>queries that cannot be classified keep their registration order last.</item>
    /// </list>
    /// </summary>
    private void AppendMedia(StringBuilder result) =>
        AppendOrderedByMedia(result, _mediaClasses, static c => c.MediaQuery, static c => c.CssString);

    /// <summary>
    /// Emits the rules registered by <see cref="AddSelector"/> before the utility
    /// rules: non-media rules first (registration order), then media rules sorted the
    /// same way as utility media rules.
    /// </summary>
    private void AppendSelectorRules(StringBuilder result)
    {
        for (int i = 0; i < _selectorRules.Count; i++)
        {
            result.Append('\n');
            result.Append(_selectorRules[i].CssString);
        }

        AppendOrderedByMedia(result, _selectorMediaRules, static r => r.MediaQuery, static r => r.CssString);
    }

    /// <summary>
    /// Appends <paramref name="items"/> ordered like Tailwind's mobile-first media
    /// rules: max-width rules first descending, then min-width rules ascending, with
    /// unclassifiable queries last in registration order.
    /// </summary>
    private static void AppendOrderedByMedia<T>(
        StringBuilder result,
        IReadOnlyList<T> items,
        Func<T, string?> mediaQueryOf,
        Func<T, string> cssOf)
    {
        int count = items.Count;

        if (count == 0)
        {
            return;
        }

        MediaEntry<T>[] entries = new MediaEntry<T>[count];

        for (int i = 0; i < count; i++)
        {
            string? query = mediaQueryOf(items[i]);
            bool known = TryParseMediaKey(query, out bool isMax, out double value);

            // 0 = max, 1 = min, 2 = unknown
            int group = known ? (isMax ? 0 : 1) : 2;
            entries[i] = new MediaEntry<T>(items[i], i, group, value);
        }

        Array.Sort(entries, static (a, b) =>
        {
            int comparison = a.Group.CompareTo(b.Group);

            if (comparison != 0)
            {
                return comparison;
            }

            comparison = a.Group switch
            {
                0 => b.Value.CompareTo(a.Value), // max: descending
                1 => a.Value.CompareTo(b.Value), // min: ascending
                _ => 0
            };

            // Stable tie breaker: keep the order in which classes were registered.
            return comparison != 0 ? comparison : a.Index.CompareTo(b.Index);
        });

        for (int i = 0; i < count; i++)
        {
            result.Append('\n');
            result.Append(cssOf(entries[i].Item));
        }
    }

    /// <summary>
    /// Extracts a sort key from a media query. Returns false for queries that are not
    /// a width comparison (for example <c>prefers-color-scheme</c>) or use a unit that
    /// cannot be compared with width (for example percentages).
    /// </summary>
    private static bool TryParseMediaKey(string? query, out bool isMax, out double value)
    {
        isMax = false;
        value = 0;

        if (string.IsNullOrWhiteSpace(query))
        {
            return false;
        }

        string q = query!.ToLowerInvariant().Replace(" ", string.Empty).Replace("(", string.Empty).Replace(")", string.Empty);

        // "not all and (min-width: ...)" is the older, negated way to describe a max width.
        if (q.Contains("notall") || q.Contains("max-width") || q.Contains("<"))
        {
            isMax = true;
        }
        else if (q.Contains("min-width") || q.Contains(">"))
        {
            isMax = false;
        }
        else
        {
            return false;
        }

        for (int i = 0; i < q.Length; i++)
        {
            if (!char.IsDigit(q[i]) && q[i] != '.')
            {
                continue;
            }

            int numberStart = i;

            while (i < q.Length && (char.IsDigit(q[i]) || q[i] == '.'))
            {
                i++;
            }

            int numberEnd = i;
            int unitStart = i;

            while (i < q.Length && char.IsLetter(q[i]))
            {
                i++;
            }

            string number = q.Substring(numberStart, numberEnd - numberStart);
            string unit = q.Substring(unitStart, i - unitStart);

            if (!double.TryParse(number, NumberStyles.Float, CultureInfo.InvariantCulture, out double parsed) || parsed < 0)
            {
                return false;
            }

            switch (unit)
            {
                case "rem":
                case "em":
                    value = parsed;
                    return true;
                case "px":
                    // Approximate conversion so px and rem breakpoints sort together.
                    value = parsed / 16.0;
                    return true;
                default:
                    return false;
            }
        }

        return false;
    }

    private readonly struct MediaEntry<T>
    {
        public MediaEntry(T item, int index, int group, double value)
        {
            Item = item;
            Index = index;
            Group = group;
            Value = value;
        }

        public T Item { get; }
        public int Index { get; }
        public int Group { get; }
        public double Value { get; }
    }

    /// <summary>
    /// Registers a rule under an arbitrary selector (for example <c>.card</c>,
    /// <c>#hero</c> or <c>p</c>) whose declarations are the properties and values of
    /// the supplied utilities. Selector rules are emitted before the utility rules so
    /// that a plain utility class can still override them, following Tailwind's
    /// component/utility layering.
    /// </summary>
    /// <param name="selector">
    /// The selector to emit, exactly as written. It is not escaped, so the caller is
    /// responsible for producing a valid selector.
    /// </param>
    /// <param name="utilities">
    /// The declarations to apply.Utilities that share a theme, pseudo and media query
    /// are merged into a single rule, and their declarations keep the order in which
    /// they appear here.
    /// </param>
    internal void AddSelector(string selector, UtilityClass[] utilities)
    {
        if (utilities.Length == 0)
        {
            return;
        }

        Dictionary<string, SelectorRule> groups = new(StringComparer.Ordinal);
        List<SelectorRule> ordered = new();

        foreach (UtilityClass utility in utilities)
        {
            // One rule per (theme, pseudo, media) combination. The key keeps the three
            // parts apart so a value that contains the separator cannot collide.
            string key = (utility.Theme ?? string.Empty) + "\u0001" +
                        (utility.Pseudo ?? string.Empty) + "\u0001" +
                        (utility.MediaQuery ?? string.Empty);

            if (!groups.TryGetValue(key, out SelectorRule? rule))
            {
                rule = new SelectorRule(selector, utility.Theme, utility.Pseudo, utility.MediaQuery);
                groups.Add(key, rule);
                ordered.Add(rule);
            }

            if (rule.Declarations.Length > 0)
            {
                rule.Declarations.Append("; ");
            }

            rule.Declarations.Append(utility.Property).Append(": ").Append(utility.Value);

            if (utility.Important)
            {
                rule.Declarations.Append(" !important");
            }

            if (utility.AdditionalProperty != null)
            {
                rule.Declarations.Append("; ")
                    .Append(utility.AdditionalProperty).Append(": ").Append(utility.AdditionalValue);

                if (utility.Important)
                {
                    rule.Declarations.Append(" !important");
                }
            }
        }

        lock (_cssBuilderLock)
        {
            foreach (SelectorRule rule in ordered)
            {
                if (string.IsNullOrWhiteSpace(rule.MediaQuery))
                {
                    _selectorRules.Add(rule);
                }
                else
                {
                    _selectorMediaRules.Add(rule);
                }
            }
        }

        InvalidateCaches();

        // Selector rules are not utility classes, but the existing subscribers (the
        // Blazor CssStyles component) only need to know that the stylesheet changed.
        // Notify them through the first utility in the batch.
        EventHandler<UtilityClass>? handler = OnClassAdded;
        handler?.Invoke(this, utilities[0]);
    }

    /// <summary>
    /// A single rule registered by <see cref="AddSelector"/>. All declarations in one
    /// rule share the same theme, pseudo and media query because they come from one
    /// call and are grouped by those three values.
    /// </summary>
    private sealed class SelectorRule
    {
        public SelectorRule(string selector, string? theme, string? pseudo, string? mediaQuery)
        {
            Selector = selector;
            Theme = theme;
            Pseudo = pseudo;
            MediaQuery = mediaQuery;
        }

        public string Selector { get; }
        public string? Theme { get; }
        public string? Pseudo { get; }
        public string? MediaQuery { get; }
        public StringBuilder Declarations { get; } = new();

        public string CssString
        {
            get
            {
                // The fluent selector builder embeds its at-rule wrapper in the
                // selector, for example "@media (min-width: 48rem) { .dark .card }".
                // Merge the declarations into that wrapper instead of appending them
                // after it (which would produce "... { ... } { ... }").
                if (Selector.Length > 0 && Selector[0] == '@')
                {
                    int closingBrace = Selector.LastIndexOf('}');

                    if (closingBrace >= 0)
                    {
                        StringBuilder wrapped = StringBuilderBag.TakeOrNew();
                        wrapped.Append(Selector, 0, closingBrace)
                            .Append("{ ")
                            .Append(Declarations)
                            .Append(" } ")
                            .Append(Selector, closingBrace, Selector.Length - closingBrace);

                        string merged = wrapped.ToString();
                        StringBuilderBag.ClearAndReturn(wrapped);
                        return merged;
                    }
                }

                StringBuilder sb = StringBuilderBag.TakeOrNew();

                if (!string.IsNullOrWhiteSpace(MediaQuery))
                {
                    sb.Append("@media ").Append(MediaQuery).Append(" { ");
                }

                if (!string.IsNullOrWhiteSpace(Theme))
                {
                    sb.Append('.').Append(UtilityClass.Escape(Theme!)).Append(' ');
                }

                sb.Append(Selector);

                if (!string.IsNullOrWhiteSpace(Pseudo))
                {
                    sb.Append(':').Append(Pseudo);
                }

                sb.Append(" { ").Append(Declarations).Append(" }");

                if (!string.IsNullOrWhiteSpace(MediaQuery))
                {
                    sb.Append(" }");
                }

                string css = sb.ToString();
                StringBuilderBag.ClearAndReturn(sb);
                return css;
            }
        }
    }

    public IEnumerator<UtilityClass> GetEnumerator() => _orderedClasses.GetEnumerator();

    IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();

}
